"""Bridge between the pytest suite and the HTML test-case project.

After **every** test the recorder rewrites

    RFM_Test_Cases_HTML/results.js          -> window.TEST_RESULTS = {...}
    RFM_Test_Cases_HTML/test_results.json   -> same data, machine readable

`index.html` loads `results.js`, so opening (or auto-refreshing) the sheet
shows the live Status of each test case while the run is still in progress.

Status mapping
--------------
    pytest passed  -> Pass
    pytest failed  -> Fail
    pytest skipped -> Blocked        (e.g. missing data / fixture)

Parametrised tests that share one TC id keep the **worst** result
(Fail > Blocked > Pass), so a single red parameter marks the case red.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

from config import settings

TC_RE = re.compile(r"\bTC-[A-Z]+-\d+\b")

STATUS_OF_OUTCOME = {"passed": "Pass", "failed": "Fail", "skipped": "Blocked"}
SEVERITY = {"Pass": 0, "Blocked": 1, "Fail": 2}          # worst wins


class RunRecorder:
    """Collects TC-id -> status while tests run and flushes them to disk."""

    def __init__(self, target: Path | None = None, enabled: bool | None = None):
        self.dir = Path(target) if target else settings.HTML_PROJECT_DIR
        self.json_path = self.dir / "test_results.json"
        self.js_path = self.dir / "results.js"
        self.enabled = settings.WRITE_HTML_RESULTS if enabled is None else enabled
        self.session: dict[str, dict] = {}
        self.started_at: str = ""
        self.unmapped: list[str] = []

    # ------------------------------------------------------------------ #
    def start(self) -> None:
        self.session = {}
        self.unmapped = []
        self.started_at = _now()

    # ------------------------------------------------------------------ #
    def record(self, item, report) -> None:
        """Hook into pytest_runtest_makereport."""
        if report.when == "setup":
            if report.skipped:
                status = "Blocked"
            elif report.failed:
                status = "Fail"                    # error during setup
            else:
                return                              # wait for the call phase
        elif report.when == "call":
            status = "Pass" if report.passed else "Fail"
        else:
            return                                  # teardown ignored

        doc = getattr(getattr(item, "function", None), "__doc__", "") or ""
        tc_ids = TC_RE.findall(doc)
        if not tc_ids:
            self.unmapped.append(item.nodeid)
            return

        at, duration = _now(), round(getattr(report, "duration", 0.0), 2)
        for tc in tc_ids:
            record = {"status": status, "at": at, "duration": duration,
                      "test": item.nodeid}
            previous = self.session.get(tc)
            if previous and SEVERITY[previous["status"]] > SEVERITY[status]:
                record["status"] = previous["status"]   # keep the worst result
            self.session[tc] = record

        self.flush()                                # <-- live update per test

    # ------------------------------------------------------------------ #
    def flush(self) -> None:
        if not self.enabled or not self.session:
            return
        try:
            cases, meta = self._load_existing()
            cases.update(self.session)
            meta.update({
                "lastRun": _now(),
                "startedAt": self.started_at or meta.get("startedAt", ""),
                "source": "pytest-playwright",
                "mapped": len(cases),
                "pass": sum(1 for r in cases.values() if r["status"] == "Pass"),
                "fail": sum(1 for r in cases.values() if r["status"] == "Fail"),
                "blocked": sum(1 for r in cases.values() if r["status"] == "Blocked"),
            })
            payload = {"meta": meta, "cases": cases}
            self.dir.mkdir(parents=True, exist_ok=True)
            text = json.dumps(payload, indent=2, ensure_ascii=False)
            self.json_path.write_text(text, encoding="utf-8")
            self.js_path.write_text(
                "// Auto-generated by the Playwright suite - do not edit by hand\n"
                f"window.TEST_RESULTS = {text};\n",
                encoding="utf-8",
            )
        except Exception as exc:                     # never break a test run
            print(f"[rfm] could not write HTML results: {exc}")

    # ------------------------------------------------------------------ #
    def finish(self) -> None:
        self.flush()
        if self.unmapped:
            print(f"[rfm] {len(self.unmapped)} test(s) had no TC id in their "
                  f"docstring: {', '.join(self.unmapped[:5])}"
                  f"{' ...' if len(self.unmapped) > 5 else ''}")
        if self.enabled:
            print(f"[rfm] HTML test case updated -> {self.js_path}")

    # ------------------------------------------------------------------ #
    def _load_existing(self) -> tuple[dict, dict]:
        """Merge with the previous run so untouched cases keep their status."""
        if self.json_path.exists():
            try:
                data = json.loads(self.json_path.read_text(encoding="utf-8"))
                return dict(data.get("cases", {})), dict(data.get("meta", {}))
            except (json.JSONDecodeError, OSError):
                pass
        return {}, {}


def _now() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


# module level singleton used by conftest
recorder = RunRecorder()
